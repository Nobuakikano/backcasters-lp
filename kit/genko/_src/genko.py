def xw(s):
    import re
    s = re.sub(r"https?://\S+", "x" * 23, s)
    w = 0
    for ch in s:
        o = ord(ch)
        w += 1 if (o <= 0x10FF or 0x2000 <= o <= 0x200D or 0x2010 <= o <= 0x201F or 0x2032 <= o <= 0x2037) else 2
    return w

